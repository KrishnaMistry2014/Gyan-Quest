const fs = require("fs");
const file = "src/components/GyanQuestCrossword.tsx";
let code = fs.readFileSync(file, "utf8");

const oldTimer = `  // Timer effect
  useEffect(() => {
    let interval: NodeJS.Timeout;
    if (view === 'playing' && isTimerRunning && gameStatus === 'playing') {
      interval = setInterval(() => {
        setTimerSeconds((prev) => prev + 1);
      }, 1000);
    }
    return () => clearInterval(interval);
  }, [view, isTimerRunning, gameStatus]);`;

const newTimer = `  const autoGeneratedChapterRef = useRef<string | null>(null);

  // Timer effect
  useEffect(() => {
    let interval: NodeJS.Timeout;
    if (view === 'playing' && isTimerRunning && gameStatus === 'playing') {
      interval = setInterval(() => {
        setTimerSeconds((prev) => prev + 1);
      }, 1000);
    }
    return () => clearInterval(interval);
  }, [view, isTimerRunning, gameStatus]);

  // Auto-generate puzzle immediately based on the uploaded chapter PDF
  useEffect(() => {
    if (initialChapter && (initialChapter.title || initialChapter.summary)) {
      const chapterKey = initialChapter.id || initialChapter.uniqueCode || initialChapter.title;
      if (autoGeneratedChapterRef.current !== chapterKey) {
        autoGeneratedChapterRef.current = chapterKey;
        handleGenerateTopic(initialChapter.title, initialChapter.summary);
      }
    }
  }, [initialChapter]);`;

if (!code.includes(oldTimer)) {
  console.error("oldTimer not found!");
  process.exit(1);
}
code = code.replace(oldTimer, newTimer);

const oldGenTopic = `  // Generate for topic or current chapter
  const handleGenerateTopic = async (topicToUse?: string) => {
    const term = topicToUse || topicInput;
    if (!term.trim()) return;

    setIsLoading(true);
    setLoadingMessage(\`Generating crossword for "\${term}"...\`);

    try {
      const res = await fetch('/api/generate-crossword', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          topic: term,
          difficulty,
        }),
      });

      const data = await res.json();
      if (!res.ok) throw new Error(data.error || 'Failed to generate crossword');
      initGame(data);
    } catch (err: any) {
      console.error(err);
      showToast(err.message || 'Error generating crossword. Using sample.', 'error');
      if (samples.length > 0) initGame(samples[0]);
      else setIsLoading(false);
    }
  };`;

const newGenTopic = `  // Generate for topic or current chapter
  const handleGenerateTopic = async (topicToUse?: string, summaryToUse?: string) => {
    const term = topicToUse || topicInput;
    const summaryText = summaryToUse || (initialChapter ? initialChapter.summary : undefined);
    if (!term.trim() && !summaryText) return;

    setIsLoading(true);
    setLoadingMessage(\`Generating crossword from \${term || "uploaded chapter"}...\`);

    try {
      const res = await fetch('/api/generate-crossword', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          topic: term,
          summary: summaryText,
          difficulty,
        }),
      });

      const data = await res.json();
      if (!res.ok) throw new Error(data.error || 'Failed to generate crossword');
      initGame(data);
    } catch (err: any) {
      console.error(err);
      showToast(err.message || 'Error generating crossword. Using sample.', 'error');
      if (samples.length > 0) initGame(samples[0]);
      else setIsLoading(false);
    }
  };`;

if (!code.includes(oldGenTopic)) {
  console.error("oldGenTopic not found!");
  process.exit(1);
}
code = code.replace(oldGenTopic, newGenTopic);

const oldNewPuzzle = `                  <button
                    type="button"
                    onClick={() => setView('welcome')}
                    className="flex-1 py-3 bg-slate-800 hover:bg-slate-700 text-white font-medium rounded-xl transition text-sm border border-slate-700 cursor-pointer"
                  >
                    New Puzzle
                  </button>`;

const newNewPuzzle = `                  <button
                    type="button"
                    onClick={() => {
                      if (initialChapter && (initialChapter.title || initialChapter.summary)) {
                        handleGenerateTopic(initialChapter.title, initialChapter.summary);
                      } else {
                        setView('welcome');
                      }
                    }}
                    className="flex-1 py-3 bg-slate-800 hover:bg-slate-700 text-white font-medium rounded-xl transition text-sm border border-slate-700 cursor-pointer"
                  >
                    {initialChapter ? 'Regenerate Puzzle' : 'New Puzzle'}
                  </button>`;

if (code.includes(oldNewPuzzle)) {
  code = code.replace(oldNewPuzzle, newNewPuzzle);
}

const oldHomeBtn = `          <button
            type="button"
            onClick={() => setView('welcome')}
            className="px-4 py-2 bg-slate-800 hover:bg-slate-700 text-slate-200 text-sm font-medium rounded-xl transition shadow-xs border border-slate-700/50 cursor-pointer"
          >
            {view === 'playing' ? 'Choose Another PDF' : 'Home'}
          </button>`;

const newHomeBtn = `          <button
            type="button"
            onClick={() => {
              if (initialChapter && (initialChapter.title || initialChapter.summary)) {
                handleGenerateTopic(initialChapter.title, initialChapter.summary);
              } else {
                setView('welcome');
              }
            }}
            className="px-4 py-2 bg-slate-800 hover:bg-slate-700 text-slate-200 text-sm font-medium rounded-xl transition shadow-xs border border-slate-700/50 cursor-pointer"
          >
            {initialChapter ? 'Regenerate Puzzle' : (view === 'playing' ? 'Choose Another PDF' : 'Home')}
          </button>`;

if (code.includes(oldHomeBtn)) {
  code = code.replace(oldHomeBtn, newHomeBtn);
}

fs.writeFileSync(file, code);
console.log("Successfully patched GyanQuestCrossword.tsx");
